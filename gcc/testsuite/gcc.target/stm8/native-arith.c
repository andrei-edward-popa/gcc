int
main (void)
{
  unsigned int i;

  for (i = 0; i < sizeof v16 / sizeof v16[0]; ++i)
    {
      const struct vector *v = &v16[i];
      short a = v->a, b = v->b;
      if ((unsigned short)__mulhi3 (a, b) != v->product
	  || __divhi3 (a, b) != v->signed_quotient
	  || __modhi3 (a, b) != v->signed_remainder
	  || __udivhi3 (a, b) != v->quotient
	  || __umodhi3 (a, b) != v->remainder)
	abort ();
    }

  for (i = 0; i < sizeof v32 / sizeof v32[0]; ++i)
    {
      const struct vector *v = &v32[i];
      long a = v->a, b = v->b;
      if ((unsigned long)__mulsi3 (a, b) != v->product
	  || __divsi3 (a, b) != v->signed_quotient
	  || __modsi3 (a, b) != v->signed_remainder
	  || __udivsi3 (a, b) != v->quotient
	  || __umodsi3 (a, b) != v->remainder)
	abort ();
    }

  return 0;
}
